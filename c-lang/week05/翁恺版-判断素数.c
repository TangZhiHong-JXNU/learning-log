#include <stdio.h>

/* 翁恺 5.2.1 判断素数（原版写法）
 *
 * 和 week05/判断素数.c 是同一件事的两种风格，区别只有：
 *   这里保留翁恺的变量名 x、判断写成 isPrime == 1。
 *
 * 思路：默认 + 证伪
 *   先假定"它是素数"，再拿 2 .. x-1 一个个去试除；
 *   除得尽 → 找到因子 → 把假设推翻 → 不必再试，提前退出。
 *
 * 输入：一个整数
 * 输出：是素数 / 不是素数
 *
 * ⚠️ 边界（原版就有的问题）：
 *   x = 1 时内层 for 一次都不跑，isPrime 停在初值 1 → 会误判成"是素数"。
 *   稳妥做法是开头特判 if (x < 2)（见 week05/判断素数.c）。
 */
int main()
{
    int x;
    scanf("%d", &x);            /* 要判断的那个数 */

    int i;                      /* 试除用的除数 */
    int isPrime = 1;            /* flag 变量：先假设"是素数" */

    for (i = 2; i < x; i++) {
        if (x % i == 0) {       /* 除得尽 → i 是 x 的因子 */
            isPrime = 0;        /* 第一步：推翻假设（把结论记下来） */
            break;              /* 第二步：再跳出循环（顺序不能反） */
        }
    }

    if (isPrime == 1) {
        printf("是素数\n");
    } else {
        printf("不是素数\n");
    }

    return 0;
}
