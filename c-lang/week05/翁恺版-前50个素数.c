#include <stdio.h>

/* 翁恺 5.2.2 结尾 try：打印前 50 个素数（原版写法：while + 末尾 x++）
 *
 * 和 week05/前50个素数.c（for 版）结果完全相同，只有"写法"不同。
 *
 * ★ 两处最容易被看错的位置：
 *   1. int i;  int isPrime = 1;  写在 while 循环体【里面】
 *      → 每一轮都重新执行一次 = 自动重置（所以不用手写 isPrime = 1;）
 *   2. x++  写在循环体【最后一行】
 *      → 这一轮的事全干完了，才换下一个数
 *
 * 循环什么时候停，只由 cnt 决定，跟 x 没有关系：
 *   x   —— 每轮一定 +1（不管是不是素数）
 *   cnt —— 只有打印真素数时才 +1
 *
 * 预期输出：50 个素数，最后一个 229
 */
int main()
{
    int x = 2;                  /* 从 2 开始挨个数（1 不是素数，直接从 2 起步） */
    int cnt = 0;                /* 计数器：已经找到几个素数了，初值必须是 0 */

    while (cnt < 50) {          /* 找够 50 个就停 —— 边界看 cnt，不看 x */

        int i;                  /* 试除用的除数，每轮重新出生 */
        int isPrime = 1;        /* 结论变量：先假设"它是素数" */

        for (i = 2; i < x; i++) {
            if (x % i == 0) {   /* 除得尽 → 找到因子 → 有反例了 */
                isPrime = 0;    /* 推翻假设 */
                break;          /* 跳出内层 for（只跳这一层） */
            }
        }
        /* 跳出 for 之后，这一轮还没完：下面的 if 和 x++ 照样要执行 */

        if (isPrime == 1) {     /* 假设没被推翻 → 它确实是素数 */
            printf("%d ", x);
            cnt++;              /* 只有真素数才配计数 */
        }

        x++;                    /* 这一轮结束，换下一个数（不管是不是素数） */
    }

    printf("\n");
    return 0;
}
