/* ============================================================
 * 翁恺《C语言程序设计》5.3.1 —— 前 n 项求和
 *
 * 例一：f(n) = 1 + 1/2 + 1/3 + ... + 1/n          （每项都是 1/i）
 * 变式：g(n) = 1 - 1/2 + 1/3 - 1/4 + ...          （一加一减）
 *
 * 编译（项目固定参数）：
 *   gcc -std=c11 -Wall -finput-charset=UTF-8 -fexec-charset=GBK 翁恺版-前n项求和.c
 * ============================================================ */

#include <stdio.h>

int main()
{
    int n;
    int i;

    scanf("%d", &n);

    /* ---------- 例一：分母从 1 一步一步走到 n ---------- */

    double sum = 0.0;          /* 累加器：加法的起点是 0.0 */

    for (i = 1; i <= n; i++) {
        sum += 1.0 / i;        /* 1.0 的那个 .0 不能省！
                                * 写成 1 / i 就是整数除法，i>=2 时全得 0，
                                * 最后整个式子只剩第一项 1.0 */
    }

    printf("f(%d)=%f\n", n, sum);

    /* ---------- 变式：给每一项配一个符号 ---------- */

    double sum2 = 0.0;
    double sign = 1.0;         /* 旗子：当前这一项用哪个符号；初值 1.0 表示第一项是加号 */

    for (i = 1; i <= n; i++) {
        sum2 += sign * (1.0 / i);   /* 用"当前符号"累加 */
        sign = -sign;               /* 翻面：+1 变 -1，-1 变 +1 */
    }

    printf("g(%d)=%f\n", n, sum2);

    /* 两个值得记住的点：
     *
     * 1) sign 是「累积型」变量 —— 初值放在循环外面，全程不重置。
     *    因为"这一项的符号"要看上一项是什么。要是把 sign = 1.0; 写进循环里，
     *    每一轮都被拉回正号，那个减号永远出不来。
     *    （对照 isPrime：那是"独立型"，每轮都要重置。）
     *
     * 2) 例一是调和级数，其实发散（涨得极慢：n=100 才 5.187378）；
     *    变式是交错级数，收敛到 ln2 ≈ 0.693147，n 越大越接近。
     */

    return 0;
}
