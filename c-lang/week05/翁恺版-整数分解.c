/*
 * 翁恺《程序设计入门 - C语言》5.3.2 整数分解（正序）
 *
 *   输入：12345        输出：1 2 3 4 5
 *   输入：700          输出：7 0 0
 *   输入：70000        输出：7 0 0 0 0
 *
 * 编译（本项目固定参数）：
 *   gcc -std=c11 -Wall -finput-charset=UTF-8 -fexec-charset=GBK 翁恺版-整数分解.c
 *
 * 注意：这一版只处理非负整数。输入负数不会报错，但结果无意义。
 */
#include <stdio.h>

int main()
{
    int x;
    scanf("%d", &x);

    /* ---- 第一步：算出最高位的权重 mask ----
     * t 是 x 的副本。因为下面要把 t 一层层切碎，
     * 而原来的 x 待会儿还得用，所以必须留个备份，不能直接切 x。
     */
    int mask = 1;
    int t = x;
    while (t > 9) {          /* 条件写 t > 9：t 只剩一位就停 */
        t /= 10;
        mask *= 10;
    }
    /* 走完这里，mask = 10 的 (位数-1) 次方
     *   7      -> 1
     *   42     -> 10
     *   700    -> 100
     *   12345  -> 10000
     */

    /* ---- 第二步：从最高位开始，一位一位取出来打印 ---- */
    do {
        int d = x / mask;        /* 取：把右边全截掉，剩下当前最高位 */
        printf("%d", d);

        if (mask > 9) {          /* 这一位后面还有位，才打分隔空格 */
            printf(" ");
        }

        x %= mask;               /* 抹：把刚才那一位从 x 上拿掉 */
        mask /= 10;              /* 尺子降一位，准备取下一个 */
    } while (mask > 0);          /* 条件用 mask，不能用 x —— 见下面说明 */

    printf("\n");
    return 0;
}

/*
 * 【为什么 while 条件必须是 mask > 0，不能是 x > 0】
 *
 * x 在循环里被 x %= mask 一路切碎。遇到末位是 0 的数，x 会提前变成 0：
 *
 *   输入 70000：第一轮取完最高位 7，x %= 10000 让 x 直接变成 0，
 *   可 mask 还在 1000、100、10、1 上，后面四位还没输出。
 *
 *   所以判断「还要不要继续」只能看 mask（它只跟第几位有关），
 *   绝不能看 x（它跟剩下的数值有关）。
 *
 * 同理，那个打空格的 if 也必须是 mask > 9，不能是 x > 9。
 *
 *   while(mask>0) + if(mask>9)  ->  [7 0 0 0 0]   ✓
 *   while(x>0)    + if(x>9)     ->  [7 ]          ✗ 后四位没进循环，0 全丢
 *   while(mask>0) + if(x>9)     ->  [7 0000]      ✗ 0 之间没有空格
 *
 * 【为什么用 do-while】
 * 保证「至少执行一次」，输入 0 时也能打出一个 0（0 本身也是一位数）。
 *
 * 【为什么用 t > 9 而不是 t > 0】
 * t > 0 会让 mask 多长一轮，一律偏大 10 倍（12345 会算出 100000）。
 */
